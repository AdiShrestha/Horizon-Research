"""Data-card statistics and card for a generated pool directory (IC-02 WP-B).

Reads <dir>/{train,dev}.npy, *_meta.parquet and *_settings.json and writes
<dir>/datacard_stats.json (finiteness, prior ranges, slope moments, conserved spatial mean, decay
ratio ||u_T||/||u_0||, Spearman independence of the parameters from IC descriptors) and
<dir>/DATA_CARD.md. Every number is computed from the stored arrays; nothing is typed in.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
import polars as pl
from scipy.stats import spearmanr

IC_COLUMNS = ("slope", "ic_grad_l2", "ic_spec_centroid")


def stats_for(directory: Path, split: str) -> dict[str, object]:
    u = np.load(directory / f"{split}.npy", mmap_mode="r")
    meta = pl.read_parquet(directory / f"{split}_meta.parquet")
    finite = bool(all(np.isfinite(u[i]).all() for i in range(u.shape[0])))
    norms0 = np.linalg.norm(np.asarray(u[:, 0]), axis=-1)
    normsT = np.linalg.norm(np.asarray(u[:, -1]), axis=-1)
    decay = normsT / norms0
    out: dict[str, object] = {
        "finite": finite,
        "shape": list(u.shape),
        "max_abs_mean": float(max(abs(np.asarray(u[i]).mean(-1)).max() for i in range(u.shape[0]))),
        "decay_min": float(decay.min()),
        "decay_median": float(np.median(decay)),
    }
    param_cols = [c for c in ("nu", "c", "delta", "nu4") if c in meta.columns]
    for c in param_cols:
        out[f"{c}_min"], out[f"{c}_max"] = float(meta[c].min()), float(meta[c].max())
    if "slope" in meta.columns:
        out["slope_mean"], out["slope_sd"] = float(meta["slope"].mean()), float(meta["slope"].std())
    for p in param_cols:
        for col in IC_COLUMNS:
            if col in meta.columns:
                out[f"spearman_{p}_{col}"] = float(spearmanr(meta[p], meta[col]).statistic)
    return out


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--dir", type=Path, required=True)
    parser.add_argument("--title", required=True)
    args = parser.parse_args()
    stats, rows = {}, []
    for split in ("train", "dev"):
        s = json.loads((args.dir / f"{split}_settings.json").read_text())
        stats[split] = stats_for(args.dir, split)
        rows.append(
            f"| {split} | {s['stream']} {s['master_seed']} | {s['n']:,} | {split}.npy "
            f"{tuple(stats[split]['shape'])} | {s['sha256']} | {s['seconds']:.0f} |"
        )
    (args.dir / "datacard_stats.json").write_text(json.dumps(stats, indent=2))
    settings = json.loads((args.dir / "train_settings.json").read_text())
    body = [
        f"# Data card: {args.title}",
        "",
        "Generated by `scripts/` in the main workspace (see the WP report for commands and commit).",
        "Settings (from train_settings.json): "
        + json.dumps({k: v for k, v in settings.items() if k not in ("seconds", "sha256")}),
        "",
        "| split | stream (master) | n | file | sha256 | seconds |",
        "|---|---|---|---|---|---|",
        *rows,
        "",
        "Checks (datacard_stats.json, computed from the stored arrays):",
        "",
        "```json",
        json.dumps(stats, indent=2),
        "```",
        "",
        "Metadata: *_meta.parquet (index, stream, parameters, slope, phi(u0) descriptors). "
        "No confirmation-stream data exist. Intended use: training (train) and development (dev).",
    ]
    (args.dir / "DATA_CARD.md").write_text("\n".join(body) + "\n")


if __name__ == "__main__":
    main()
