"""The development environment matches the stated requirements."""

from __future__ import annotations

import importlib
import importlib.metadata as metadata
import shutil
import subprocess
import sys
import tomllib
from pathlib import Path

import pytest
from packaging.markers import Marker
from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

ROOT = Path(__file__).resolve().parents[1]
LOCK = ROOT / "source" / "requirements.lock"


def _pins_from_pyproject() -> dict[str, str]:
    """Exact ``name==version`` requirements declared as constraints or tooling dependencies."""
    config = tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))
    entries = list(config["tool"]["uv"]["constraint-dependencies"])
    entries += config["dependency-groups"]["tooling"]
    pins: dict[str, str] = {}
    for entry in entries:
        requirement = Requirement(entry)
        specs = list(requirement.specifier)
        assert len(specs) == 1 and specs[0].operator == "==", entry
        pins[canonicalize_name(requirement.name)] = specs[0].version
    return pins


def _parse_requirements(text: str) -> dict[str, str]:
    """Pinned name -> version entries of a requirements export that apply to this platform."""
    packages: dict[str, str] = {}
    for raw in text.splitlines():
        if not raw or raw[0] in " #":
            continue
        entry = raw.rstrip(" \\")
        requirement_text, _, marker_text = entry.partition(";")
        if marker_text and not Marker(marker_text.strip()).evaluate():
            continue
        requirement = Requirement(requirement_text.strip())
        specs = list(requirement.specifier)
        assert len(specs) == 1 and specs[0].operator == "==", entry
        packages[canonicalize_name(requirement.name)] = specs[0].version
    return packages


def _locked_packages() -> dict[str, str]:
    """Packages of source/requirements.lock that apply to this platform."""
    return _parse_requirements(LOCK.read_text(encoding="utf-8"))


def _optional_only_packages(locked: set[str]) -> set[str]:
    """Packages that only optional extras or non-default dependency groups bring in."""
    uv = shutil.which("uv")
    if uv is None:
        return set()
    result = subprocess.run(
        [
            uv,
            "export",
            "--format",
            "requirements-txt",
            "--frozen",
            "--no-emit-project",
            "--offline",
            "--no-hashes",
            "--all-groups",
            "--all-extras",
        ],
        cwd=ROOT,
        capture_output=True,
        text=True,
        check=True,
    )
    return set(_parse_requirements(result.stdout)) - locked


def test_interpreter_is_python_3_12() -> None:
    assert sys.version_info[:2] == (3, 12)


def test_package_version_is_single_sourced() -> None:
    import trajcp

    assert trajcp.__version__ == metadata.version("trajcp")


def test_no_bytecode_under_source() -> None:
    source = ROOT / "source"
    if not source.exists():
        pytest.skip("no source/ directory")
    stale = [
        str(p.relative_to(ROOT))
        for p in source.rglob("*")
        if p.name == "__pycache__" or p.suffix in {".pyc", ".pyo"}
    ]
    assert not stale, f"bytecode under source/ (run `make clean-source-bytecode`): {stale}"


def test_exact_pins_are_installed() -> None:
    for name, version in _pins_from_pyproject().items():
        assert metadata.version(name) == version, name


def test_environment_equals_the_sub_study_lock() -> None:
    locked = _locked_packages()
    installed = {
        canonicalize_name(dist.metadata["Name"]): dist.version for dist in metadata.distributions()
    }
    installed.pop("trajcp", None)
    # Optional extras and non-default groups may be installed on a developer machine; the lock
    # covers the default set.
    mismatched = {n: (v, installed.get(n)) for n, v in locked.items() if installed.get(n) != v}
    assert not mismatched, f"installed versions differ from the lock: {mismatched}"
    unlocked = sorted(set(installed) - set(locked) - _optional_only_packages(set(locked)))
    assert not unlocked, f"installed packages missing from the lock: {unlocked}"


def test_sub_study_lock_matches_project_lock() -> None:
    uv = shutil.which("uv")
    if uv is None:
        pytest.skip("uv is not on PATH")
    result = subprocess.run(
        [
            uv,
            "export",
            "--format",
            "requirements-txt",
            "--frozen",
            "--no-emit-project",
            "--offline",
        ],
        cwd=ROOT,
        capture_output=True,
        text=True,
        check=True,
    )

    def body(text: str) -> list[str]:
        skip = ("# This file was autogenerated", "#    uv export")
        return [line for line in text.splitlines() if not line.startswith(skip)]

    assert body(result.stdout) == body(LOCK.read_text(encoding="utf-8")), (
        "source/requirements.lock is out of date; regenerate with `make export-lock`"
    )


