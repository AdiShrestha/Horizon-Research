def test_jax_is_cpu_only_and_supports_float64() -> None:
    import jax
    import jax.numpy as jnp

    jax.config.update("jax_enable_x64", True)
    assert {device.platform for device in jax.devices()} == {"cpu"}
    assert jnp.arange(4, dtype=jnp.float64).dtype == jnp.float64
    assert (jnp.float64(1.0) + jnp.float64(2.0**-40)) != jnp.float64(1.0)


def test_numpy_defaults_to_float64() -> None:
    import numpy as np

    assert np.zeros(2).dtype == np.float64


def test_exponax_is_importable() -> None:
    import exponax

    assert metadata.version("exponax")
    assert hasattr(exponax.stepper, "Burgers")


def test_torch_meets_the_version_floor_and_keeps_float32_default() -> None:
    import torch

    major, minor = (int(part) for part in torch.__version__.split(".")[:2])
    assert (major, minor) >= (2, 13)
    # The conformal core converts to float64 explicitly; torch itself stays at float32.
    assert torch.get_default_dtype() == torch.float32


